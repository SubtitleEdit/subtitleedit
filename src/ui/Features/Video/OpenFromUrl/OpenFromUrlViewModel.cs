using Avalonia.Controls;
using Avalonia.Input;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using Nikse.SubtitleEdit.Logic.Config;
using Nikse.SubtitleEdit.Logic;
using Nikse.SubtitleEdit.Logic.Download;
using System;
using System.Collections.ObjectModel;
using System.Linq;

namespace Nikse.SubtitleEdit.Features.Video.OpenFromUrl;

public enum OpenFromUrlMode
{
    OpenOnline,
    DownloadAndOpen,
}

/// <summary>
/// A "Cookies from browser" choice: <see cref="Id"/> is yt-dlp's browser name, empty for none.
/// </summary>
public sealed record CookiesBrowserItem(string Id, string Name)
{
    public override string ToString() => Name;
}

public partial class OpenFromUrlViewModel : ObservableObject
{
    // The two mode cards stay disabled until there is a URL (and, for "Download and open",
    // something to download) - clicking them before used to do nothing at all (#17001).
    [ObservableProperty]
    [NotifyCanExecuteChangedFor(nameof(OpenOnlineCommand))]
    [NotifyCanExecuteChangedFor(nameof(DownloadAndOpenCommand))]
    private string _url;

    [ObservableProperty]
    [NotifyCanExecuteChangedFor(nameof(DownloadAndOpenCommand))]
    private bool _downloadVideo;

    [ObservableProperty]
    [NotifyCanExecuteChangedFor(nameof(DownloadAndOpenCommand))]
    private bool _downloadSubtitles;

    [ObservableProperty] private bool _includeAutoGeneratedSubtitles;
    [ObservableProperty] private ObservableCollection<CookiesBrowserItem> _cookiesBrowsers;
    [ObservableProperty] private CookiesBrowserItem _selectedCookiesBrowser;

    public Window? Window { get; set; }

    public OpenFromUrlMode? SelectedMode { get; private set; }

    public bool OkPressed => SelectedMode != null;

    public OpenFromUrlViewModel()
    {
        Url = string.Empty;
        DownloadVideo = Se.Settings.Video.OpenFromUrlDownloadVideo;
        DownloadSubtitles = Se.Settings.Video.OpenFromUrlDownloadSubtitles;
        IncludeAutoGeneratedSubtitles = Se.Settings.Video.OpenFromUrlIncludeAutoGeneratedSubtitles;

        CookiesBrowsers = new ObservableCollection<CookiesBrowserItem> { new(string.Empty, Se.Language.General.None) };
        foreach (var browser in YtDlpDownloadService.CookieBrowsers)
        {
            if (browser == "safari" && !OperatingSystem.IsMacOS())
            {
                continue;
            }

            CookiesBrowsers.Add(new CookiesBrowserItem(browser, YtDlpDownloadService.GetBrowserDisplayName(browser)));
        }

        var current = YtDlpDownloadService.GetCookiesBrowser();
        SelectedCookiesBrowser = CookiesBrowsers.FirstOrDefault(p => p.Id == current) ?? CookiesBrowsers[0];
    }

    private void SaveSettings()
    {
        Se.Settings.Video.OpenFromUrlDownloadVideo = DownloadVideo;
        Se.Settings.Video.OpenFromUrlDownloadSubtitles = DownloadSubtitles;
        Se.Settings.Video.OpenFromUrlIncludeAutoGeneratedSubtitles = IncludeAutoGeneratedSubtitles;
        Se.Settings.Video.OpenFromUrlCookiesFromBrowser = SelectedCookiesBrowser?.Id ?? string.Empty;
    }

    private bool CanOpenOnline() => !string.IsNullOrWhiteSpace(Url);

    private bool CanDownloadAndOpen() => CanOpenOnline() && (DownloadVideo || DownloadSubtitles);

    [RelayCommand(CanExecute = nameof(CanOpenOnline))]
    private void OpenOnline()
    {
        if (!CanOpenOnline())
        {
            return;
        }

        SaveSettings();
        SelectedMode = OpenFromUrlMode.OpenOnline;
        Window?.Close();
    }

    [RelayCommand(CanExecute = nameof(CanDownloadAndOpen))]
    private void DownloadAndOpen()
    {
        if (!CanDownloadAndOpen())
        {
            return;
        }

        SaveSettings();
        SelectedMode = OpenFromUrlMode.DownloadAndOpen;
        Window?.Close();
    }

    [RelayCommand]
    private void Cancel()
    {
        Window?.Close();
    }

    internal void OnKeyDown(KeyEventArgs e) => UiUtil.CloseOnEscapeOrShowHelp(e, Window, "features/video-player", "opening-video");
}
