using Avalonia;
using Avalonia.Automation;
using Avalonia.Controls;
using Avalonia.Controls.Presenters;
using Avalonia.Data;
using Avalonia.Input;
using Avalonia.Layout;
using Avalonia.Media;
using Avalonia.Styling;
using CommunityToolkit.Mvvm.Input;
using Nikse.SubtitleEdit.Logic;
using Nikse.SubtitleEdit.Logic.Config;

namespace Nikse.SubtitleEdit.Features.Video.OpenFromUrl;

/// <summary>
/// Open a video from a URL, in the editor look (see <see cref="EditorChrome"/>): the URL, the
/// two ways to open it as cards, and the download options.
/// </summary>
public class OpenFromUrlWindow : Window
{
    private const double CardCornerRadius = 8;

    private readonly OpenFromUrlViewModel _vm;
    private readonly TextBox _urlTextBox;

    public OpenFromUrlWindow(OpenFromUrlViewModel vm)
    {
        UiUtil.InitializeWindow(this, GetType().Name);
        Title = Se.Language.Video.OpenFromUrlTitle;
        SizeToContent = SizeToContent.WidthAndHeight;
        CanResize = false;
        Width = 520;
        WindowStartupLocation = WindowStartupLocation.CenterOwner;
        EditorChrome.ApplyWindow(this, EditorWindowStyles.VideoTool);
        AddStyles();

        _vm = vm;
        vm.Window = this;
        DataContext = vm;

        _urlTextBox = new TextBox
        {
            PlaceholderText = "https://...",
            HorizontalAlignment = HorizontalAlignment.Stretch,
            [!TextBox.TextProperty] = new Binding(nameof(vm.Url)) { Mode = BindingMode.TwoWay },
        };
        _urlTextBox.Classes.Add("text");
        AutomationProperties.SetName(_urlTextBox, Se.Language.General.Url);

        var openOnlineCard = BuildCard(
            "fa-solid fa-play",
            Se.Language.Video.OpenFromUrlOpenOnline,
            Se.Language.Video.OpenFromUrlOpenOnlineDescription,
            Se.Language.Video.OpenFromUrlOpenOnlineNote,
            vm.OpenOnlineCommand,
            isRecommended: false);

        var downloadCard = BuildCard(
            "fa-solid fa-download",
            Se.Language.Video.OpenFromUrlDownloadAndOpen,
            Se.Language.Video.OpenFromUrlDownloadAndOpenDescription,
            Se.Language.Video.OpenFromUrlDownloadAndOpenNote,
            vm.DownloadAndOpenCommand,
            isRecommended: true);

        var urlSection = new StackPanel { Spacing = 12 };
        urlSection.Children.Add(_urlTextBox);
        urlSection.Children.Add(openOnlineCard);
        urlSection.Children.Add(downloadCard);

        var downloadVideo = EditorChrome.MakeSwitchRow(nameof(vm.DownloadVideo), Se.Language.Video.OpenFromUrlDownloadVideo);
        var downloadSubtitles = EditorChrome.MakeSwitchRow(nameof(vm.DownloadSubtitles), Se.Language.Video.OpenFromUrlDownloadSubtitles);
        var includeAutoGenerated = EditorChrome.MakeSwitchRow(nameof(vm.IncludeAutoGeneratedSubtitles), Se.Language.Video.OpenFromUrlIncludeAutoGeneratedSubtitles);
        includeAutoGenerated.Margin = new Thickness(24, 0, 0, 0);
        includeAutoGenerated.Bind(IsEnabledProperty, new Binding(nameof(vm.DownloadSubtitles)));

        var cookiesComboBox = UiUtil.MakeComboBox(vm.CookiesBrowsers, vm, nameof(vm.SelectedCookiesBrowser));
        cookiesComboBox.MinWidth = 140;
        cookiesComboBox.HorizontalAlignment = HorizontalAlignment.Left;
        cookiesComboBox[AutomationProperties.NameProperty] = Se.Language.Video.OpenFromUrlCookiesFromBrowser;
        var cookiesRow = EditorChrome.MakeLabeledRow(Se.Language.Video.OpenFromUrlCookiesFromBrowser, cookiesComboBox, 150);
        if (Se.Settings.Appearance.ShowHints)
        {
            ToolTip.SetTip(cookiesRow, Se.Language.Video.OpenFromUrlCookiesFromBrowserHint);
        }

        var options = new StackPanel { Spacing = 8 };
        options.Children.Add(downloadVideo);
        options.Children.Add(downloadSubtitles);
        options.Children.Add(includeAutoGenerated);
        options.Children.Add(cookiesRow);

        var sections = new StackPanel { Background = EditorChrome.PanelBrush };
        sections.Children.Add(EditorChrome.MakeEditorSection(Se.Language.General.Url, urlSection, first: true));
        sections.Children.Add(EditorChrome.MakeEditorSection(Se.Language.General.Options, options));

        var root = new Grid
        {
            RowDefinitions = { new RowDefinition(new GridLength(1, GridUnitType.Star)), new RowDefinition(GridLength.Auto) },
        };
        root.Add(new ScrollViewer
        {
            Content = sections,
            VerticalScrollBarVisibility = Avalonia.Controls.Primitives.ScrollBarVisibility.Auto,
            HorizontalScrollBarVisibility = Avalonia.Controls.Primitives.ScrollBarVisibility.Disabled,
        }, 0, 0);
        root.Add(EditorChrome.MakeButtonBar(null, UiUtil.MakeButtonCancel(vm.CancelCommand)), 1, 0);

        Content = root;

        // Focus the URL box on first activation (the pattern used by the other windows) -
        // the Loaded + Input-priority post this used to do never stuck on macOS. Guarded so
        // re-activating the window later doesn't yank focus back out of whatever the user
        // was on.
        UiUtil.FocusOnFirstActivation(this, () =>
        {
            _urlTextBox.Focus();
            _urlTextBox.CaretIndex = _urlTextBox.Text?.Length ?? 0;
        });
    }

    /// <summary>
    /// The cards: field-colored, a hover tint, and an accent border on hover.
    /// </summary>
    private void AddStyles()
    {
        Styles.Add(new Style(x => x.OfType<Button>().Class("card").Template().OfType<ContentPresenter>().Name("PART_ContentPresenter"))
        {
            Setters =
            {
                new Setter(ContentPresenter.BackgroundProperty, EditorChrome.FieldBrush),
                new Setter(ContentPresenter.ForegroundProperty, EditorChrome.StrongTextBrush),
            },
        });
        Styles.Add(new Style(x => x.OfType<Button>().Class("card").Class(":pointerover").Template().OfType<ContentPresenter>().Name("PART_ContentPresenter"))
        {
            Setters =
            {
                new Setter(ContentPresenter.BackgroundProperty, EditorChrome.HoverBrush),
                new Setter(ContentPresenter.BorderBrushProperty, EditorChrome.AccentBrush),
                new Setter(ContentPresenter.ForegroundProperty, EditorChrome.StrongTextBrush),
            },
        });
        Styles.Add(new Style(x => x.OfType<Button>().Class("card").Class(":pressed").Template().OfType<ContentPresenter>().Name("PART_ContentPresenter"))
        {
            Setters = { new Setter(ContentPresenter.BackgroundProperty, EditorChrome.PressedBrush) },
        });
    }

    private static Button BuildCard(string icon, string title, string description, string note, IRelayCommand command, bool isRecommended)
    {
        var accent = isRecommended ? EditorChrome.AccentBrush : EditorChrome.IconBrush;

        var iconTile = new Border
        {
            Width = 36,
            Height = 36,
            CornerRadius = new CornerRadius(8),
            Background = isRecommended ? EditorChrome.AccentSoftBrush : EditorChrome.HoverBrush,
            VerticalAlignment = VerticalAlignment.Top,
            Margin = new Thickness(0, 0, 14, 0),
            Child = new Optris.Icons.Avalonia.Icon
            {
                Value = icon,
                FontSize = 15,
                Foreground = accent,
                HorizontalAlignment = HorizontalAlignment.Center,
                VerticalAlignment = VerticalAlignment.Center,
            },
        };

        var titleText = new TextBlock
        {
            Text = title,
            FontSize = 14,
            FontWeight = FontWeight.SemiBold,
            Margin = new Thickness(0, 0, 0, 3),
        };

        var descriptionText = new TextBlock
        {
            Text = description,
            FontSize = 12.5,
            TextWrapping = TextWrapping.Wrap,
            Margin = new Thickness(0, 0, 0, 6),
        };

        var noteIcon = new Optris.Icons.Avalonia.Icon
        {
            Value = "fa-solid fa-circle-info",
            FontSize = 11,
            Foreground = accent,
            VerticalAlignment = VerticalAlignment.Top,
            Margin = new Thickness(0, 2, 6, 0),
        };

        var noteText = new TextBlock
        {
            Text = note,
            FontSize = 12,
            Foreground = EditorChrome.DimTextBrush,
            TextWrapping = TextWrapping.Wrap,
        };

        var noteRow = new DockPanel();
        DockPanel.SetDock(noteIcon, Dock.Left);
        noteRow.Children.Add(noteIcon);
        noteRow.Children.Add(noteText);

        var textStack = new StackPanel
        {
            Orientation = Orientation.Vertical,
            HorizontalAlignment = HorizontalAlignment.Stretch,
            Children = { titleText, descriptionText, noteRow },
        };

        var row = new DockPanel
        {
            LastChildFill = true,
        };
        DockPanel.SetDock(iconTile, Dock.Left);
        row.Children.Add(iconTile);
        row.Children.Add(textStack);

        var button = new Button
        {
            Content = row,
            // The card's content is a panel; announce it by its title (#12087).
            [AutomationProperties.NameProperty] = title,
            Padding = new Thickness(14),
            HorizontalAlignment = HorizontalAlignment.Stretch,
            HorizontalContentAlignment = HorizontalAlignment.Stretch,
            VerticalContentAlignment = VerticalAlignment.Top,
            BorderBrush = isRecommended ? EditorChrome.AccentBrush : EditorChrome.FieldBorderBrush,
            BorderThickness = new Thickness(isRecommended ? 2 : 1),
            CornerRadius = new CornerRadius(CardCornerRadius),
            Cursor = new Cursor(StandardCursorType.Hand),
            Command = command,
        };
        button.Classes.Add("card");

        return button;
    }

    protected override void OnKeyDown(KeyEventArgs e)
    {
        base.OnKeyDown(e);
        _vm.OnKeyDown(e);
    }
}
